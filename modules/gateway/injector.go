// translated comment
type responseRecorderWithInjection struct {
	http.ResponseWriter
	injector    *HTMLInjector
	body        bytes.Buffer
	statusCode  int
	wroteHeader bool
}

func (rec *responseRecorderWithInjection) Write(b []byte) (int, error) {
	return rec.body.Write(b)
}

func (rec *responseRecorderWithInjection) WriteHeader(code int) {
	if !rec.wroteHeader {
		rec.statusCode = code
		rec.wroteHeader = true
	}
}

func (rec *responseRecorderWithInjection) shouldInject() bool {
	contentType := rec.Header().Get("Content-Type")
	return strings.Contains(strings.ToLower(contentType), "text/html")
}

