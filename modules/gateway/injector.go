var (
	injectorHeadPattern = regexp.MustCompile(`(?i)<head[^>]*>`)
	injectorHTMLPattern = regexp.MustCompile(`(?i)<html[^>]*>`)
)

func buildInjectionCode(cfg *InjectorConfig, generator *frontend.JSAntiDetectCodeGenerator) string {
	var buf bytes.Buffer

	if cfg.AddInjectionMarker {
		buf.WriteString("\n<!-- P3 Anti-Detection Injection Start -->\n")
	}

	buf.WriteString("<script>\n")
	buf.WriteString("// P3 Modern JS High-Entropy Anti-Detection Code\n")
	buf.WriteString("// Generated by fingerprint gateway\n")

	if generator != nil {
		antiDetectCode := generator.GenerateFullAntiDetectionCode()
		buf.WriteString(antiDetectCode)
		buf.WriteString("\n")
	}

	if cfg.InjectConsistency && generator != nil {
		buf.WriteString("\n// Cross-Layer Consistency Validation\n")
		consistencyCode := generator.GenerateCrossLayerConsistencyCode()
		buf.WriteString(consistencyCode)
		buf.WriteString("\n")
	}

	buf.WriteString("</script>\n")

	if cfg.AddInjectionMarker {
		buf.WriteString("<!-- P3 Anti-Detection Injection End -->\n")
	}

	return buf.String()
}

