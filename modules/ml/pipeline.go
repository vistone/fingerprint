// Package ml — pipeline.go provides end-to-end model inference and training pipelines.
//
// ┌─────────────────────────────────────────────────────────────────────┐
// │                  ModelPipeline — Inference Orchestration             │
// │                                                                     │
// │  Raw request                                                        │
// │    ↓ EncodeFingerprint()                                            │
// │  30-dim feature vector                                              │
// │    ↓ FingerprintEncoder.EncodeSingle()                              │
// │  32-dim embedding                                                   │
// │    ├→ BrowserClassifier.ClassifySingle()  → browser identification │
// │    │                                                                │
// │    │  30-dim features + 10-dim cross-layer features                 │
// │    ├→ ForgeryDetector.DetectSingle()      → forgery detection      │
// │    │                                                                │
// │    │  32-dim embedding + forgery result + 8-dim behavior features   │
// │    └→ ThreatAssessor.AssessSingle()       → threat + action        │
// │                                                                     │
// │  All model results aggregated into PipelineResult                   │
// └─────────────────────────────────────────────────────────────────────┘
//
// ┌─────────────────────────────────────────────────────────────────────┐
// │                  Trainer — Training Pipeline                        │
// │                                                                     │
// │  207 browser profiles → data augmentation → training samples        │
// │                                                                     │
// │  Phase 1: Encoder pre-training (triplet loss)                       │
// │    - Positive pairs: same browser + Gaussian noise                  │
// │    - Negative samples: different browser family                     │
// │                                                                     │
// │  Phase 2: Classifier training (cross-entropy)                       │
// │    - Freeze encoder, train classification head                      │
// │                                                                     │
// │  Phase 3: Forgery detector training (binary cross-entropy)          │
// │    - Real samples: from profiles                                    │
// │    - Forged samples: cross-browser layer mixing, headless features  │
// │                                                                     │
// │  Phase 4: Threat assessor training (cross-entropy)                  │
// │    - Initial labels: generated by rule engine                       │
// │    - Ongoing: online feedback fine-tuning                           │
// └─────────────────────────────────────────────────────────────────────┘
